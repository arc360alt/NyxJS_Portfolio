/** Renders text into columns of lit rows (bitmask per column). */
export function textToColumns(text: string): number[] {
  const cols: number[] = [];
  for (const ch of text.toUpperCase()) {
    const glyph = font[ch] ?? font[' '];
    const width = glyph[0].length;
    for (let x = 0; x < width; x++) {
      let mask = 0;
      for (let y = 0; y < 5; y++) if (glyph[y][x] === '#') mask |= 1 << y;
      cols.push(mask);
    }
    cols.push(0); // letter spacing
  }
  return cols;
}
